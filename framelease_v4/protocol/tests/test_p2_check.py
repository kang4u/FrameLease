def decision_rows(job, n=12, choice=True, bad_mu=False, gap=False):
    """v3-schema rows of a behaviour run: every second epoch is a choice epoch with the logged behaviour keys."""
    name = job['policy_params']['utility']
    eps, _, d = B.parse_behaviour(name)
    rows, draw = [], 0
    for e in range(1, n + 1):
        depth = 1 + (e % 9)
        feats = {k: 0.0 for k in FEATURE_NAMES}
        feats['depth'] = depth
        row = {'kind': 'decision', 'epoch': e, 'sim_s': 0.5 * e, 'depth': depth, 'features': feats}
        if choice and e % 2 == 0:
            base = B.a_det_action(depth, d)
            explore = int(e % 4 == 0)
            action = (VS.REFRESH if base == VS.REFINE else VS.REFINE) if explore else base
            feats.update({'v4_mu': (1 - eps) * float(action == base) + eps / 2 + (0.05 if bad_mu else 0.0),
                          'v4_explore': explore, 'v4_base_action': base, 'v4_draw': draw})
            draw += 1
            row.update(p_both=True, feasible=[VS.REFINE, VS.REFRESH], action=action, reason=f'both_feasible:{name}')
        else:
            row.update(p_both=False, feasible=[VS.REFRESH], action=VS.REFRESH,
                       reason='only_refresh_feasible:refine_depth')
        rows.append(row)
    if gap:
        del rows[3]
    return rows


def make_run(root, job, name, status='Completed', choice=True, metric_info=True, ticks=True, bad_mu=False, gap=False,
             kappa=None, logs=True, lock_busy=False):
    """A synthetic launcher run directory of a P2 job (the files the launcher and the agent write)."""
    run = Path(root) / job['output_dir'] / 'runs' / name
    fl = run / 'raw' / 'agent' / 'framelease'
    fl.mkdir(parents=True)
    (run / 'metrics').mkdir()
    utility = job['policy_params']['utility']
    cfg = {'v4_arm': job['arm_name'], 'route': {'route_id': job['route_id'], 'town': job['town']},
           'kappa': job['kappa'] if kappa is None else kappa, 'seed': job['seed'],
           'v4': {'agent': {'policy_params': dict(job['policy_params'])}},
           'fast_prefix': {'options': list(CS.FAST_PREFIX_OPTIONS)}, 'envelope_sha256': job['envelope']['sha256']}
    (run / 'config.json').write_text(json.dumps(cfg))
    code = {str(ROOT / rel): sha for rel, sha in job['require_sha256'].items()}
    (run / 'manifest.json').write_text(json.dumps({'status': 'COMPLETED', 'identity': {'code': code}}))
    (run / 'raw' / 'source_v4').mkdir(parents=True)
    (run / 'raw' / 'source_v4' / 'hashes.json').write_text(json.dumps(
        {rel: sha for rel, sha in job['require_sha256'].items() if rel.startswith('framelease_v4/')}))
    records = 0 if (lock_busy or status is None) else 1
    (run / 'metrics' / 'result.json').write_text(json.dumps(
        {'route_records': records, 'route_status': status if records else None,
         'scores': {'score_composed': 42.0, 'score_route': 60.0, 'score_penalty': 0.7} if records else None,
         'timed_out': status is None and not lock_busy, 'wall_s': 300.0, 'fast_prefix': {'problems': []},
         'error': f'RuntimeError: {SS_LOCK} by pid 1' if lock_busy else None}))
    if not logs or lock_busy:
        return run
    (run / 'raw' / 'official_results.json').write_text('{}')
    if metric_info:
        (run / 'raw' / 'agent' / 'metric_info.json').write_text('{}')
    rows = decision_rows(job, choice=choice, bad_mu=bad_mu, gap=gap)
    (fl / 'decisions.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in rows))
    if ticks:
        (fl / 'ticks.jsonl').write_text(''.join(json.dumps({'tick': k, 'sim_s': 0.05 * (k + 1), 'wall_s': 0.06}) + '\n'
                                                for k in range(40)))
    summary = {'policy': {'utility': utility},
               'v4': {'schema': CS.V4_RUNTIME_SCHEMA, 'runtime_class': 'V4Runtime', 'ticks': 40,
                      'decisions': 12, 'p_both': 0.5 if choice else 0.0},
               'fast_prefix': {'validation_ok': True}, 'actor_log': {'enabled': True}}
    (fl / 'summary.json').write_text(json.dumps(summary))
    (fl / 'fast_prefix.json').write_text(json.dumps(
        {'stage': 'final', 'fast_prefix': {'active': {o: True for o in CS.FAST_PREFIX_OPTIONS},
                                           'validation': {'ok': True, 'failures': []}},
         'stats': {'sdpa': {'sdpa_calls': 1234}}}))
    (fl / 'jobs.jsonl').write_text('{"job": 1}\n')
    (fl / 'events.jsonl').write_text('{"event": "start"}\n')
    return run


SS_LOCK = 'shared GPU lock is held'


class Block:
    """The P2 block written by p2_jobs.py from a synthetic freeze, run directories and runner records, all in tmp."""

    def __init__(self, tmp, label='E5', d=4):
        self.tmp = Path(tmp)
        self.env = T2J.Env(self.tmp / 'inputs', label, d)
        self.freeze = self.env.freeze()
        self.lines, spec = P2.build_block(self.freeze)
        self.root = self.tmp / 'root'
        self.paths = P2.block_paths(self.tmp / 'p2_jobs')
        P2.write_block(self.paths, self.lines, spec, [], [], root=self.root)
        self.job_file = self.paths[0]
        self.queue = self.tmp / 'qp2'
        (self.queue / 'jobs.d').mkdir(parents=True)
        shutil.copy(self.job_file, self.queue / 'jobs.d' / self.job_file.name)
        self.records = []
        self.n = 0

    def run(self, job, **kw):
        self.n += 1
        return make_run(self.root, job, f'20261113T{self.n:06d}_{self.n:08x}', **kw)

    def attempt(self, job, outcome, run=None, counted=True, final=True, status=None):
        a = sum(1 for r in self.records if r['event'] == 'start' and r['id'] == job['id']) + 1
        self.records.append({'event': 'start', 'id': job['id'], 'attempt': a})
        self.records.append({'event': 'end', 'id': job['id'], 'attempt': a, 'outcome': outcome, 'counted': counted,
                             'final': final, 'run_dir': str(run) if run else None,
                             'result': {'route_status': status} if status else None,
                             'end_utc': f'2026-11-13T00:{a:02d}:00+00:00', 'wall_s': 300.0,
                             'file': self.job_file.name, 'other_new_run_dirs': None})

    def ok(self, job, **kw):
        run = self.run(job, **kw)
        self.attempt(job, 'ok', run)
        return run

    def complete(self, skip=()):
        for j in self.lines:
            if j['id'] not in skip:
                self.ok(j)

    def check(self):
        (self.queue / 'status.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in self.records))
        return P2C.check(self.job_file, self.queue, self.root)

    def main(self, *extra):
        (self.queue / 'status.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in self.records))
        err, out = io.StringIO(), io.StringIO()
        with contextlib.redirect_stderr(err), contextlib.redirect_stdout(out):
            rc = P2C.main(['--job-file', str(self.job_file), '--queue', str(self.queue), '--root', str(self.root),
                           '--report', str(self.tmp / 'out' / 'p2_check.json'),
                           '--manifest', str(self.tmp / 'out' / 'data_manifest.json')] + list(extra))
        return rc, out.getvalue(), err.getvalue()


def row_of(rep, job):
    return next(r for r in rep['jobs'] if r['job'] == job['id'])


class CompleteBlockTest(unittest.TestCase):
    def test_complete_block_passes_and_writes_the_manifest(self):
        with tempfile.TemporaryDirectory() as tmp:
            S = Block(tmp)
            S.complete()
            rep, man = S.check()
            self.assertEqual(rep['verdict'], 'PASS',
                             json.dumps(rep['errors'] + rep['problems'] + rep['failed_criteria']))
            self.assertEqual(rep['counts'], {'episode': 132, 'missing': 0, 'pending': 0, 'error': 0,
                                             'failed_criteria': 0})
            self.assertEqual(rep['excluded_runs'], [])
            self.assertEqual(rep['warnings'], [])
            for r in rep['jobs']:
                self.assertEqual(set(r['criteria']), set(P2C.CRITERIA))
                self.assertEqual({c['status'] for c in r['criteria'].values()}, {CS.PASS})
            self.assertEqual((man['n_episodes'], man['n_missing'], man['episodes_per_kappa']),
                             (132, 0, {'1.0': 44, '1.5': 44, '2.0': 44}))
            self.assertEqual(man['tuning_freeze']['sha256'], S.env.sha)
            self.assertEqual(man['job_file_sha256'], PJ.sha256_file(S.job_file))
            eps = man['episodes']
            self.assertEqual([(e['kappa'], int(e['route_id'])) for e in eps],
                             sorted((e['kappa'], int(e['route_id'])) for e in eps))
            by_job = {j['id']: j for j in S.lines}
            for e in eps:
                j = by_job[e['job']]
                self.assertEqual((e['kappa'], e['route_id'], e['behaviour_seed'], e['utility']),
                                 (j['kappa'], j['route_id'], j['behaviour']['seed'], j['policy_params']['utility']))
                self.assertEqual((e['n_decisions'], e['n_choice'], e['flags']), (12, 6, []))
                self.assertTrue(e['run_dir'].startswith(str(S.root / j['output_dir'] / 'runs') + '/'))
                for rel, required in P2C.SOURCE_LOGS:
                    if required:
                        self.assertEqual(e['source_logs_sha256'][rel], PJ.sha256_file(Path(e['run_dir']) / rel))
            # writing: an equal report is kept (its sha256 may be cited), a different one is refused
            out = Path(tmp) / 'out'
            p, written = P2C.write_json(rep, out / 'p2_check.json')
            self.assertTrue(written)
            sha = PJ.sha256_file(p)
            p, written = P2C.write_json({**rep, 'written': 'later'}, p)
            self.assertFalse(written)
            self.assertEqual(PJ.sha256_file(p), sha)
            with self.assertRaises(FileExistsError):
                P2C.write_json({**rep, 'verdict': 'FAIL'}, p)
            rc, stdout, err = S.main('--write')
            self.assertEqual(rc, 0, err)
            self.assertIn('P2 check: PASS', stdout)
            self.assertEqual(json.loads((out / 'data_manifest.json').read_text())['n_episodes'], 132)


class AttemptsTest(unittest.TestCase):
    def test_failed_attempts_versus_final_runs_and_missing_episodes(self):
        with tempfile.TemporaryDirectory() as tmp:
            S = Block(tmp)
            A, Bj, C, D, E, F = S.lines[:6]
            a1 = S.run(A, status='Failed - Simulation crashed')               # a full run directory, failed
            S.attempt(A, 'infra_failure', a1, final=False, status='Failed - Simulation crashed')
            a2 = S.ok(A)                                                      # the retry: the episode
            b1 = S.run(Bj, status='Failed - Agent crashed')
            S.attempt(Bj, 'infra_failure', b1, final=False, status='Failed - Agent crashed')
            b2 = S.run(Bj, status='Failed - Agent crashed')
            S.attempt(Bj, 'infra_failure', b2, final=True, status='Failed - Agent crashed')
            c1 = S.run(C, lock_busy=True)                                     # not counted by the runner
            S.attempt(C, 'gpu_lock_busy', c1, counted=False, final=False)
            c2 = S.ok(C)
            S.attempt(D, 'launch_error', None, final=False)
            S.attempt(D, 'launch_error', None, final=True)
            e1 = S.run(E, status=None)                                        # wall-cap timeout, no record
            S.attempt(E, 'timeout', e1, final=False)
            e2 = S.run(E, status=None)
            S.attempt(E, 'timeout', e2, final=True)
            stray = S.run(F)                                                  # a complete run no record names
            S.complete(skip={x['id'] for x in (A, Bj, C, D, E)})
            rep, man = S.check()
            self.assertEqual(rep['verdict'], 'PASS', rep['errors'] + rep['failed_criteria'])
            self.assertEqual(rep['counts']['episode'], 129)
            self.assertEqual([m['job'] for m in rep['missing']], [Bj['id'], D['id'], E['id']])
            causes = {m['job']: m['cause'] for m in man['missing']}
            self.assertEqual(causes, {Bj['id']: 'infra_failure (Failed - Agent crashed)', D['id']: 'launch_error',
                                      E['id']: 'timeout'})
            self.assertEqual(len(man['missing'][0]['attempts']), 2)
            episodes = {e['job']: e for e in man['episodes']}
            self.assertEqual(len(episodes), 129)
            self.assertNotIn(Bj['id'], episodes)
            self.assertEqual(episodes[A['id']]['run_dir'], str(a2))
            self.assertIn('retried', episodes[A['id']]['flags'])
            self.assertEqual(episodes[C['id']]['run_dir'], str(c2))
            self.assertNotIn('retried', episodes[C['id']]['flags'])
            self.assertEqual([a['outcome'] for a in episodes[C['id']]['attempts']], ['gpu_lock_busy', 'ok'])
            used = {e['run_dir'] for e in man['episodes']}
            excluded = {x['run_dir']: x for x in man['excluded_runs']}
            self.assertEqual(set(excluded), {str(p) for p in (a1, b1, b2, c1, e1, e2, stray)})
            self.assertFalse(used & set(excluded))
            self.assertEqual(excluded[str(a1)]['reason'], 'failed attempt, retried (PROTOCOL Sec. 8.4)')
            self.assertTrue(excluded[str(c1)]['reason'].startswith('attempt not counted by the runner'))
            self.assertEqual(excluded[str(b2)]['reason'], 'final attempt without a valid official record (missing '
                                                           'episode)')
            self.assertIsNone(excluded[str(stray)]['job'])
            self.assertTrue(any('named by no runner record' in w for w in rep['warnings']))
            # a directory listing also returns the failed attempts and the stray run: the manifest never does
            dirs = sorted({j['output_dir'] for j in S.lines})
            listed = {str(p) for p in DS.discover_runs([S.root / d for d in dirs])}
            self.assertTrue({str(a1), str(b1), str(b2), str(stray)} <= listed)
            self.assertEqual(listed - set(excluded), used)

    def test_pending_jobs_make_the_check_incomplete(self):
        with tempfile.TemporaryDirectory() as tmp:
            S = Block(tmp)
            A, Bj, C = S.lines[:3]
            b1 = S.run(Bj, status='Failed - Simulation crashed')
            S.attempt(Bj, 'infra_failure', b1, final=False, status='Failed - Simulation crashed')   # awaits its retry
            S.attempt(C, 'launch_error', None, final=False)
            S.attempt(C, 'launch_error', None, final=True)
            S.records.append({'event': 'start', 'id': C['id'], 'attempt': 3})   # --retry-failed after the final
            S.complete(skip={A['id'], Bj['id'], C['id']})
            rep, man = S.check()
            self.assertEqual(rep['verdict'], 'INCOMPLETE')
            self.assertIsNone(man)
            self.assertEqual(rep['counts']['pending'], 3)
            self.assertIn('no runner record yet', row_of(rep, A)['cause'])
            self.assertIn('1 counted of 1 attempts', row_of(rep, Bj)['cause'])
            self.assertIn('--retry-failed', row_of(rep, C)['cause'])
            rc, out, err = S.main('--write')
            self.assertEqual(rc, 3)
            self.assertIn('no data manifest written', out)
            self.assertFalse((Path(tmp) / 'out' / 'data_manifest.json').exists())
            self.assertTrue((Path(tmp) / 'out' / 'p2_check.json').exists())

    def test_runner_ok_without_a_matching_valid_run_is_an_error(self):
        with tempfile.TemporaryDirectory() as tmp:
            S = Block(tmp)
            A, Bj, C, D = S.lines[:4]
            S.attempt(A, 'ok', S.root / A['output_dir'] / 'runs' / 'nowhere')
            S.attempt(Bj, 'ok', S.run(Bj, kappa=9.0))                         # another configuration
            other = next(j for j in S.lines if j['kappa'] != C['kappa'])
            S.attempt(C, 'ok', S.run(other))                                  # a run in another output directory
            S.attempt(D, 'ok', S.run(D, status='Failed - Simulation crashed'))  # 'ok' without a valid record
            S.complete(skip={x['id'] for x in (A, Bj, C, D)})
            rep, man = S.check()
            self.assertEqual(rep['verdict'], 'FAIL')
            self.assertIsNone(man)
            self.assertEqual(rep['counts']['error'], 4)
            self.assertIn('not a run directory', row_of(rep, A)['cause'])
            self.assertIn('another configuration', row_of(rep, Bj)['cause'])
            self.assertIn(f'is not in {C["output_dir"]}/runs', row_of(rep, C)['cause'])
            self.assertIn('no valid official record', row_of(rep, D)['cause'])
            rc, out, err = S.main()
            self.assertEqual(rc, 1)
            self.assertIn('ERROR', out)


class CriteriaTest(unittest.TestCase):
    def test_each_criterion_fails_on_its_own_defect(self):
        with tempfile.TemporaryDirectory() as tmp:
            S = Block(tmp)
            jobs = S.lines[:9]
            runs = {j['id']: S.ok(j, **kw) for j, kw in zip(jobs, (
                {'bad_mu': True}, {'gap': True}, {'ticks': False}, {}, {}, {}, {'choice': False},
                {'metric_info': False}, {}))}
            S.complete(skip={j['id'] for j in jobs})

            def edit(path, fn):
                d = json.loads(path.read_text())
                fn(d)
                path.write_text(json.dumps(d))
            fp = runs[jobs[3]['id']] / 'raw/agent/framelease/fast_prefix.json'
            edit(fp, lambda d: d.update(stage='warmup'))
            hashes = runs[jobs[4]['id']] / 'raw/source_v4/hashes.json'
            edit(hashes, lambda d: d.update({'framelease_v4/rl/behaviour.py': '0' * 64}))
            (runs[jobs[5]['id']] / 'raw' / 'official_results.json').unlink()
            summary = runs[jobs[8]['id']] / 'raw/agent/framelease/summary.json'
            edit(summary, lambda d: d['policy'].update(utility='heuristic'))
            rep, man = S.check()
            self.assertEqual(rep['verdict'], 'FAIL')
            self.assertIsNone(man)
            want = {0: 'behaviour', 1: 'decisions', 2: 'source_logs', 3: 'fast_prefix', 4: 'config', 5: 'record',
                    8: 'behaviour'}
            for i, criterion in want.items():
                row = row_of(rep, jobs[i])
                self.assertEqual(row['status'], 'failed_criteria', (i, row.get('criteria')))
                self.assertIn(criterion, row['failed'], (i, row['failed']))
            self.assertEqual(sorted(rep['failed_criteria']), sorted(jobs[i]['id'] for i in want))
            self.assertIn('v4_mu', row_of(rep, jobs[0])['criteria']['behaviour']['detail'])
            self.assertIn('ticks.jsonl', row_of(rep, jobs[2])['criteria']['source_logs']['detail'])
            # no choice epoch: N/A and flagged; no metric_info.json: flagged terminal-only reward; both pass
            r6, r7 = row_of(rep, jobs[6]), row_of(rep, jobs[7])
            self.assertEqual((r6['status'], r6['criteria']['behaviour']['status']), ('episode', CS.NA))
            self.assertEqual(r7['status'], 'episode')
            self.assertIn(P2C.METRIC_INFO, r7['criteria']['source_logs']['values']['optional_absent'])
            # the same block without the defective runs passes, with the two flags in the manifest
            S2 = Block(Path(tmp) / 'b')
            S2.ok(S2.lines[0], choice=False)
            S2.ok(S2.lines[1], metric_info=False)
            S2.complete(skip={S2.lines[0]['id'], S2.lines[1]['id']})
            rep2, man2 = S2.check()
            self.assertEqual(rep2['verdict'], 'PASS')
            flags = {e['job']: e['flags'] for e in man2['episodes']}
            self.assertEqual(flags[S2.lines[0]['id']], ['no_choice_epoch'])
            self.assertEqual(flags[S2.lines[1]['id']], ['terminal_only_reward'])


class RefusalTest(unittest.TestCase):
    def test_test_routes_other_specs_and_missing_records(self):
        with tempfile.TemporaryDirectory() as tmp:
            S = Block(tmp)
            S.complete()
            S.check()
            test = PJ.route_split()['test'][0]['route_id']
            # a job file with a test route (and a stage spec made for it): refused
            lines = [json.loads(x) for x in S.job_file.read_text().splitlines()]
            lines[3]['route_id'] = test
            bad = Path(tmp) / 'bad' / 'b10_rl_data.jsonl'
            bad.parent.mkdir()
            bad.write_text(P2.jsonl(lines))
            spec = json.loads(S.paths[1].read_text())
            spec['job_file_sha256'] = PJ.sha256_file(bad)
            bad.with_name('b10_rl_data.stage.json').write_text(json.dumps(spec))
            with self.assertRaises(PermissionError):
                P2C.load_block(bad)
            # an output directory outside rl_data/: refused
            lines = [json.loads(x) for x in S.job_file.read_text().splitlines()]
            lines[0]['output_dir'] = 'outputs/framelease_v4/matrix/fl_behaviour'
            bad.write_text(P2.jsonl(lines))
            spec['job_file_sha256'] = PJ.sha256_file(bad)
            bad.with_name('b10_rl_data.stage.json').write_text(json.dumps(spec))
            with self.assertRaises(PermissionError):
                P2C.load_block(bad)
            # the stage spec of another job file
            bad.write_text(S.job_file.read_text() + '\n')
            with self.assertRaises(ValueError):
                P2C.load_block(bad)
            # no status.jsonl: the runner's records are required (exit code 2, no traceback)
            (S.queue / 'status.jsonl').unlink()
            err = io.StringIO()
            with contextlib.redirect_stderr(err), contextlib.redirect_stdout(io.StringIO()):
                rc = P2C.main(['--job-file', str(S.job_file), '--queue', str(S.queue), '--root', str(S.root)])
            self.assertEqual(rc, 2)
            self.assertIn('status.jsonl', err.getvalue())
            self.assertNotIn('Traceback', err.getvalue())

    def test_the_queue_copy_of_the_job_file_must_be_the_job_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            S = Block(tmp)
            S.complete()
            copy = S.queue / 'jobs.d' / S.job_file.name
            copy.write_text(copy.read_text().replace('"tier": 2', '"tier": 3', 1))
            rep, man = S.check()
            self.assertEqual(rep['verdict'], 'FAIL')
            self.assertIsNone(man)
            self.assertTrue(any('the queue ran another job file' in p for p in rep['problems']))
            copy.unlink()
            rep, man = S.check()
            self.assertEqual(rep['verdict'], 'PASS')
            self.assertTrue(any('not compared' in w for w in rep['warnings']))


