"""Evaluator agent of the extension arms (framelease_v4/arms_ext): the pinned v4 agent with the extension's arm registry.

PROTOCOL Secs. 4.1, 7.4 (fl_global_shield in closed loop) and 2.3 (one runtime class, V4Runtime). Built only inside the
evaluator's agent process, from the entry file that run_closed_loop_ext.py writes into the run (ENTRY_NAME):

  raw/framelease_v4_arms_ext_agent_entry.py  ->  framelease_v4.arms_ext.agent_ext.get_entry_point()

FrameLeaseV4ExtAgent is a subclass of the pinned framelease_v4.arms.agent_v4.FrameLeaseV4Agent (built by
agent_v4.build_agent_class: framelease_v2 latency agent, run_step with the actor-log row, destroy with the actor-log
flush, all inherited unchanged). It overrides setup() only, whose body is the pinned FrameLeaseV4Agent.setup with one
substitution: setup_ext instead of agent_v4.setup_v4. setup_ext is agent_v4.setup_v4 line for line (same order, same
agent attributes, V4Runtime, the same agent_config.json row) except that the configuration and the policy come from
arms_ext.agent_config_from / arms_ext.build_policy: identical to arms_v4's for every arms_v4 arm, and for
fl_global_shield the base arm's checks plus GlobalMarginShieldPolicy (the agent refuses a changed E*, lease file or
global-lease parameters). No attribute of agent_v4 / arms_v4 is rebound; the pinned agent class is untouched. For an
arms_v4 arm this agent behaves exactly as the pinned one (tested with the fake model: identical ticks, jobs, decisions
and summary), but the pinned launcher keeps using the pinned agent for those arms.

Drift guard: tests/test_drift_guard.py requires setup_ext and FrameLeaseV4ExtAgent.setup to equal agent_v4.setup_v4 and
FrameLeaseV4Agent.setup up to the substitutions it lists (the function name, the agent_v4 helpers called through AG,
arms_ext's agent_config_from / build_policy, setup_ext).
"""
