"""Evaluator agent entry of the framelease_v4 RL arms (behaviour data collection and learned-utility runs).

The agent is the UNCHANGED v3 agent (framelease_v3.runtime.v3_agent FrameLeaseV3Agent, or the fast-prefix agent of
framelease_v3.fastprefix.agent_entry with base 'v3' when $FRAMELEASE_FASTPREFIX_CONFIG is set). This entry only

  1. registers the v4 utility named in the v3 agent configuration ($FRAMELEASE_V3_RUNTIME_CONFIG,
     v3.policy_params.utility) in framelease_v3.runtime.v3_shield.UTILITIES, before the agent class is built and
     again at the start of setup() (idempotent), so the v3 setup builds ShieldedHeuristicPolicy with that utility;
  2. after the base setup(), checks that the policy really holds that utility, writes
     <SAVE_PATH>/framelease/v4_rl.json (utility, code hashes) and adds a 'v4_rl' block (utility statistics) to
     summary.json through an instance attribute on the runtime (the class method is untouched; no value changes).

Nothing else changes: lease, shield, decision rule (Eq. 8), commit gate, watchdog, timeline and logging are v3's.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

ENV_V3_CONFIG = 'FRAMELEASE_V3_RUNTIME_CONFIG'              # = framelease_v3.runtime.v3_agent.ENV_V3_CONFIG
ENV_FASTPREFIX_CONFIG = 'FRAMELEASE_FASTPREFIX_CONFIG'      # = framelease_v3.fastprefix.agent_entry.ENV_FASTPREFIX_CONFIG
MANIFEST_NAME = 'v4_rl.json'
MANIFEST_SCHEMA = 'framelease_v4.rl_agent/1'


def configured_utility(path=None):
    path = path or os.environ.get(ENV_V3_CONFIG)
    if not path:
        raise RuntimeError(f'{ENV_V3_CONFIG} is not set; the v4 entry runs only v3-runtime arms')
    cfg = json.loads(Path(path).read_text(encoding='utf-8'))
    v3 = cfg.get('v3') or {}
    return str((v3.get('policy_params') or {}).get('utility', 'heuristic'))


def register_configured_utility(path=None):
    from framelease_v4.rl.behaviour import register_utility_name
    name = configured_utility(path)
    register_utility_name(name)
    return name


def _base_class():
    if os.environ.get(ENV_FASTPREFIX_CONFIG):
        from framelease_v3.fastprefix import agent_entry as FPE
        base = FPE.load_fastprefix_config()['base']
        if base != 'v3':
            raise ValueError(f'the v4 RL entry needs the v3 base agent (fast-prefix base is {base!r})')
        return FPE.build_agent_class('v3')
    from framelease_v3.runtime import v3_agent
    return v3_agent.build_v3_agent_class()


def install_v4(agent, name):
    """After the base setup: verify the utility, write the manifest, extend summary.json (instance attribute)."""
    from framelease_v4.rl.common import code_hashes, jsonable
    runtime = getattr(agent, '_fl_runtime', None)
    policy = getattr(runtime, 'policy', None)
    utility = getattr(policy, 'utility', None)
    if utility is None or getattr(utility, 'name', None) != name:
        raise RuntimeError(f'v4 utility {name!r} not installed (policy utility: {getattr(utility, "name", None)!r})')
    out_dir = Path(agent._fl_dir)
    state = {'stage': 'setup'}

    def stats():
        return utility.stats() if hasattr(utility, 'stats') else {'name': utility.name}

    def write_manifest():
        row = {'schema': MANIFEST_SCHEMA, 'stage': state['stage'], 'utility': name,
               'utility_class': type(utility).__module__ + '.' + type(utility).__name__,
               'agent_class': type(agent).__name__, 'stats': stats(), 'code_sha256': code_hashes()}
        tmp = out_dir / (MANIFEST_NAME + '.tmp')
        tmp.write_text(json.dumps(jsonable(row), indent=1, sort_keys=True), encoding='utf-8')
        os.replace(tmp, out_dir / MANIFEST_NAME)

    original_summary = runtime.summary

    def summary():
        s = original_summary()
        s['v4_rl'] = {'utility': name, 'stats': stats(), 'manifest': MANIFEST_NAME}
        state['stage'] = 'final'
        write_manifest()
        return s

    runtime.summary = summary                               # instance attribute; adds a key, changes no value
    write_manifest()
    return utility


def build_agent_class():
    name = register_configured_utility()
    Base = _base_class()

    def setup(self, path_to_conf_file):
        register_configured_utility()
        Base.setup(self, path_to_conf_file)
        install_v4(self, name)

    return type('FrameLeaseV4RLAgent', (Base,), {'setup': setup, '__module__': __name__,
                                                 '__doc__': f'{Base.__name__} + framelease_v4 utility {name}'})


def get_entry_point():
    """Evaluator hook (the class is built only inside the evaluator process: torch / carla / mmcv imports)."""
    cls = build_agent_class()
    globals()[cls.__name__] = cls
    return cls.__name__


