def _json_arg(text):
    if text is None:
        return {}
    if text.startswith('@'):
        text = Path(text[1:]).read_text(encoding='utf-8')
    value = json.loads(text)
    if not isinstance(value, dict):
        raise argparse.ArgumentTypeError('expected a JSON object')
    return value


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split('\n\n')[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--policy', required=True, choices=RUNTIME_MODES)
    p.add_argument('--routes', type=Path, default=DEFAULT_ROUTES, help='Bench2Drive routes XML')
    p.add_argument('--route-id', required=True, help='route id inside --routes (one route per launch)')
    p.add_argument('--kappa', type=float, default=1.0, help='GPU contention scale on measured CUDA times')
    p.add_argument('--seed', type=int, default=11)
    p.add_argument('--port', type=int, default=2400, help='CARLA RPC port; +1, +2 and +6000 (TM) must be free')
    p.add_argument('--output-dir', type=Path, default=ROOT / 'outputs/framelease_v2/closed_loop')
    p.add_argument('--policy-params', type=_json_arg, default={}, help='JSON object or @file (policies.PARAMS)')
    p.add_argument('--runtime-params', type=_json_arg, default={}, help='JSON object or @file (RuntimeConfig)')
    p.add_argument('--lease-params', type=Path, help='calibrated LeaseParams JSON (framelease_v2/calibration.py)')
    p.add_argument('--temporal-mode', choices=('latest', 'official'), default='latest',
                   help="latency modes: 'latest' uses the newest perception memory (one bank); 'official' keeps the "
                        "per-call 10-bank rotation. oracle_sync always uses the official agent unchanged.")
    p.add_argument('--precision', choices=('bf16-autocast', 'official'), default='bf16-autocast')
    p.add_argument('--no-warmup', action='store_true')
    p.add_argument('--no-metric-info', action='store_true')
    p.add_argument('--carla-root', type=Path, default=Path(os.environ.get('CARLA_ROOT', '/home/kang/opt/CARLA_0.9.15')))
    p.add_argument('--checkpoint', type=Path, default=Path(os.environ['CHECKPOINT']) if os.environ.get('CHECKPOINT') else None)
    p.add_argument('--timeout-s', type=float, default=7200.0, help='wall-clock budget of the whole evaluation')
    p.add_argument('--evaluator-timeout', type=float, default=180.0, help="evaluator's --timeout (agent watchdog)")
    p.add_argument('--lock-wait-s', type=float, default=0.0, help='wait up to this long for the shared GPU lock')
    p.add_argument('--dry-run', action='store_true')
    return p.parse_args(argv)


def route_info(routes, route_id):
    tree = ET.parse(routes)
    for route in tree.iter('route'):
        if route.attrib.get('id') == str(route_id):
            scen = [s.attrib.get('type') for s in route.iter('scenario')]
            return {'route_id': str(route_id), 'town': route.attrib.get('town'), 'scenarios': scen}
    raise ValueError(f'route id {route_id!r} not found in {routes}')


def lease_h_max(path):
    """h_max_s of a LeaseParams file, else of framelease_v2.lease.LeaseParams() (None if unavailable)."""
    try:
        if path:
            return float(json.loads(Path(path).read_text(encoding='utf-8'))['h_max_s'])
        from framelease_v2.lease import LeaseParams
        return float(LeaseParams().h_max_s)
    except (ImportError, KeyError, OSError, ValueError):
        return None


def agent_config(args):
    runtime = {'kappa': float(args.kappa), **args.runtime_params}
    if 'kappa' in args.runtime_params and float(args.runtime_params['kappa']) != float(args.kappa):
        raise ValueError('kappa given twice with different values (--kappa and --runtime-params)')
    h_max = lease_h_max(args.lease_params) if args.policy != 'oracle_sync' else None
    if h_max is not None and 'max_age_s' not in runtime:
        # Default: one global maximum observation age (blueprint Sec. 4.3) for every method, i.e. the baselines'
        # expiry equals the cap of the action-conditioned lease. An explicit max_age_s (H_max sensitivity, or
        # letting the baselines expire at the 3 s plan horizon) is kept and flagged in the run configuration.
        runtime['max_age_s'] = h_max
    cfg = AgentConfig.from_dict({
        'mode': args.policy, 'policy_params': validate_policy_params(args.policy, args.policy_params),
        'runtime': RuntimeConfig.from_dict(runtime).to_dict(), 'seed': int(args.seed),
        'temporal_mode': args.temporal_mode, 'precision': args.precision,
        'lease_params_path': str(args.lease_params.resolve()) if args.lease_params else None,
        'warmup': not args.no_warmup, 'record_metric_info': not args.no_metric_info})
    if args.policy == 'oracle_sync' and (args.runtime_params or args.lease_params or args.kappa != 1.0):
        raise ValueError('oracle_sync is the official zero-latency agent; runtime/lease parameters do not apply')
    return cfg.to_dict()


def evaluator_command(args, run_dir, checkpoint):
    raw = run_dir / 'raw'
    return [sys.executable, '-u', '-c', BOOTSTRAP, str(args.seed), str(raw / 'leaderboard_evaluator_owned.py'),
            '--routes', str(args.routes.resolve()), '--routes-subset', str(args.route_id), '--repetitions', '1',
            '--track', 'SENSORS', '--checkpoint', str(raw / 'official_results.json'),
            '--debug-checkpoint', str(raw / 'live_results.txt'), '--agent', str(raw / 'framelease_v2_agent_entry.py'),
            '--agent-config', f'{MODEL_CONFIG}+{checkpoint}', '--debug', '0', '--port', str(args.port),
            '--traffic-manager-port', str(args.port + 6000), '--traffic-manager-seed', str(args.seed),
            '--gpu-rank', '0', '--timeout', str(args.evaluator_timeout)]


def evaluator_env(args, run_dir):
    raw = run_dir / 'raw'
    env = os.environ.copy()
    env.update(SAVE_PATH=str(raw / 'agent'), CARLA_ROOT=str(args.carla_root), IS_BENCH2DRIVE='1', IS_VISUALIZE='0',
               PLANNER_TYPE='traj', ROUTES=str(args.routes.resolve()), PYTHONUNBUFFERED='1',
               **{ENV_RUNTIME_CONFIG: str(raw / 'agent_runtime_config.json')})
    env['PYTHONPATH'] = str(ROOT) + os.pathsep + env.get('PYTHONPATH', '')
    overrides = {k: env[k] for k in ('SAVE_PATH', 'CARLA_ROOT', 'IS_BENCH2DRIVE', 'IS_VISUALIZE', 'PLANNER_TYPE', 'ROUTES',
                                     'PYTHONUNBUFFERED', 'PYTHONPATH', ENV_RUNTIME_CONFIG)}
    return env, overrides


def preflight(args):
    """Every check that needs neither the GPU nor CARLA; raises on the first problem."""
    problems = []
    if args.checkpoint is None or not args.checkpoint.is_file():
        problems.append(f'checkpoint not found: {args.checkpoint} (source linux/env.sh)')
    for path, what in ((EVALUATOR, 'official evaluator'), (MODEL_CONFIG, 'model config'),
                       (OFFICIAL_AGENT, 'official agent'), (args.routes, 'routes file'),
                       (args.carla_root / 'CarlaUE4.sh', 'CARLA server')):
        if not Path(path).is_file():
            problems.append(f'{what} not found: {path}')
    if args.lease_params and not args.lease_params.is_file():
        problems.append(f'lease params not found: {args.lease_params}')
    if not (Path(sys.prefix) / 'conda-meta').is_dir():
        problems.append('run inside the project Conda environment')
    if problems:
        raise SystemExit('preflight failed:\n  ' + '\n  '.join(problems))
    info = route_info(args.routes, args.route_id)
    if args.policy == 'framelease' and not args.lease_params:
        info['lease_params_warning'] = 'UNCALIBRATED placeholder bounds (no --lease-params); smoke use only'
    return info


def cached_file_hash(path, cache_file):
    """sha256 of a large file, cached by (path, size, mtime) so repeated runs do not re-read 6 GB."""
    path = Path(path).resolve()
    st = path.stat()
    key = f'{path}|{st.st_size}|{st.st_mtime_ns}'
    cache = read_json(cache_file) if Path(cache_file).is_file() else {}
    if key not in cache:
        cache[key] = file_hash(path)
        atomic_json(cache_file, cache)
    return cache[key]


@contextlib.contextmanager
def gpu_lock(wait_s, log):
    """framelease_common.writer_lock, optionally waiting for the current holder to release it."""
    deadline = time.monotonic() + max(0.0, wait_s)
    announced = False
    while True:
        cm = writer_lock(GPU_LOCK_ROOT)
        try:
            cm.__enter__()
            break
        except FileExistsError:
            if time.monotonic() >= deadline:
                holder = (GPU_LOCK_ROOT / '.writer.lock')
                raise RuntimeError('shared GPU lock is held: ' + (holder.read_text() if holder.exists() else '?'))
            if not announced:
                log('gpu_lock_wait', holder=(GPU_LOCK_ROOT / '.writer.lock').read_text()
                    if (GPU_LOCK_ROOT / '.writer.lock').exists() else None)
                announced = True
            time.sleep(10)
    try:
        yield
    except BaseException:
        if not cm.__exit__(*sys.exc_info()):
            raise
    else:
        cm.__exit__(None, None, None)


def summarize(run_dir, process, timed_out, error, cleanup, owned, started):
    raw = run_dir / 'raw'
    score_path = raw / 'official_results.json'
    scores = read_json(score_path) if score_path.exists() else None
    records = (scores or {}).get('_checkpoint', {}).get('records', [])
    summary_path = raw / 'agent/framelease/summary.json'
    agent_summary = json.loads(summary_path.read_text()) if summary_path.exists() else None
    record = records[0] if records else {}
    return {'returncode': process.returncode if process else None, 'timed_out': timed_out,
            'wall_s': time.monotonic() - started, 'error': error, 'cleanup_errors': cleanup,
            'route_records': len(records), 'route_status': record.get('status'),
            'scores': record.get('scores'), 'infractions': record.get('infractions'), 'meta': record.get('meta'),
            'official_results': scores, 'agent_summary': agent_summary,
            'ownership': {str(k): v for k, v in owned.items()}}


def main(argv=None):
    args = parse_args(argv)
    args.output_dir = args.output_dir.resolve()
    try:
        cfg = agent_config(args)
        info = preflight(args)
    except ValueError as e:
        raise SystemExit(f'invalid configuration: {e}')
    title = POLICY_TITLES.get(args.policy, args.policy)
    clock = 'OFFICIAL_SYNCHRONOUS_ZERO_LATENCY' if args.policy == 'oracle_sync' else 'VIRTUAL_TIME_MEASURED_LATENCY'
    if args.dry_run:
        placeholder = args.output_dir.resolve() / 'runs' / '<UTC>_<ID>'
        env, overrides = evaluator_env(args, placeholder)
        print(json.dumps({'status': 'NOT_STARTED', 'dry_run': True, 'policy': args.policy, 'title': title,
                          'clock': clock, 'route': info, 'agent_config': cfg, 'cwd': str(B2D),
                          'command': evaluator_command(args, placeholder, args.checkpoint),
                          'environment_overrides': overrides,
                          'ports': [args.port, args.port + 1, args.port + 2, args.port + 6000]}, indent=1))
        return 0

    from stage02_real_vla import UNIDRIVE_COMMIT
    from stage05_carla_closed_loop import native_evaluator_owned_cleanup, require_free_ports, stop_owned_group
    import psutil

    checkpoint = args.checkpoint.resolve()
    hash_cache = args.output_dir / '.file_hash_cache.json'
    args.output_dir.mkdir(parents=True, exist_ok=True)
    h_max = lease_h_max(args.lease_params) if args.policy != 'oracle_sync' else None
    max_age = cfg['runtime']['max_age_s']
    max_age_note = None if h_max is None or abs(max_age - h_max) < 1e-9 else \
        f'EXPLICIT_OVERRIDE: runtime max_age_s={max_age} differs from lease h_max_s={h_max}'
    if max_age_note:
        print('WARNING: ' + max_age_note, file=sys.stderr)
    config = {'mode': 'closed-loop', 'policy': args.policy, 'title': title, 'clock': clock, 'route': info,
              'lease_h_max_s': h_max, 'max_age_note': max_age_note,
              'routes': str(args.routes.resolve()), 'routes_sha256': file_hash(args.routes),
              'kappa': args.kappa, 'seed': args.seed, 'port': args.port, 'tm_port': args.port + 6000,
              'agent_config': cfg, 'checkpoint': str(checkpoint),
              'checkpoint_sha256': cached_file_hash(checkpoint, hash_cache),
              'lease_params_sha256': file_hash(args.lease_params) if args.lease_params else None,
              'model_source_commit': UNIDRIVE_COMMIT, 'evaluator_sha256': file_hash(EVALUATOR),
              'official_agent_sha256': file_hash(OFFICIAL_AGENT), 'wall_timeout_s': args.timeout_s,
              'ground_truth_contract': 'simulator state only in the official scorer and in evaluation-only '
                                       'metric_info; never in the model input, the lease or the controller'}
    dependencies = [ROOT / d for d in CODE_DEPENDENCIES if (ROOT / d).is_file()]
    dependencies += [EVALUATOR, OFFICIAL_AGENT, OFFICIAL_AGENT.with_name('pid_controller.py'), MODEL_CONFIG,
                     args.routes.resolve()]
    if args.lease_params:
        dependencies.append(args.lease_params.resolve())
    evidence = ['CARLA_CLOSED_LOOP', 'REAL_VLA', 'REAL_GPU',
                'OFFICIAL_ZERO_LATENCY_UPPER_BOUND' if args.policy == 'oracle_sync' else 'VIRTUAL_TIME_MEASURED_LATENCY']
    ns = SimpleNamespace(output_dir=args.output_dir, seed=args.seed, mode='closed-loop', resume=False)
    run = StageRun(STAGE, ns, config, evidence, dependencies)
    run_dir = run.path.resolve()
    raw = run_dir / 'raw'
    (raw / 'agent').mkdir(parents=True, exist_ok=True)
    atomic_json(raw / 'agent_runtime_config.json', cfg)
    (raw / 'framelease_v2_agent_entry.py').write_text(ENTRY_SOURCE, encoding='utf-8')
    original = EVALUATOR.read_text()
    patched = native_evaluator_owned_cleanup(original)
    (raw / 'leaderboard_evaluator_owned.py').write_text(patched)
    (raw / 'evaluator_cleanup.patch').write_text(''.join(difflib.unified_diff(
        original.splitlines(True), patched.splitlines(True), fromfile=str(EVALUATOR),
        tofile=str(raw / 'leaderboard_evaluator_owned.py'))))
    cmd = evaluator_command(args, run_dir, checkpoint)
    env, overrides = evaluator_env(args, run_dir)
    atomic_json(raw / 'command.json', {'argv': cmd, 'cwd': str(B2D), 'environment_overrides': overrides,
                                       'patched_evaluator_sha256': file_hash(raw / 'leaderboard_evaluator_owned.py')})

    process = None
    owned = {}
    error = None
    timed_out = False
    cleanup = []
    started = time.monotonic()
    try:
        with gpu_lock(args.lock_wait_s, run.log):
            try:
                require_free_ports([args.port, args.port + 1, args.port + 2, args.port + 6000])
                with (run_dir / 'logs/evaluator.log').open('w') as log:
                    process = subprocess.Popen(cmd, cwd=B2D, env=env, stdout=log, stderr=subprocess.STDOUT,
                                               start_new_session=True)
                run.log('evaluator_started', pid=process.pid)
                while process.poll() is None:
                    try:
                        for child in psutil.Process(process.pid).children(recursive=True):
                            owned[child.pid] = child.create_time()
                    except psutil.NoSuchProcess:
                        pass
                    if time.monotonic() - started > args.timeout_s:
                        timed_out = True
                        break
                    time.sleep(2)
            except BaseException:
                error = traceback.format_exc()
                run.log('failure', traceback=error)
            finally:
                if process is not None:
                    try:
                        stop_owned_group(process)
                    except Exception as e:  # noqa: BLE001
                        cleanup.append(repr(e))
                for pid, created in owned.items():
                    try:
                        child = psutil.Process(pid)
                        if child.create_time() == created and child.status() != psutil.STATUS_ZOMBIE:
                            child.kill()
                            child.wait(timeout=10)
                    except psutil.NoSuchProcess:
                        pass
                    except Exception as e:  # noqa: BLE001
                        cleanup.append(repr(e))
    except BaseException:
        error = error or traceback.format_exc()
        run.log('failure', traceback=error)

    result = summarize(run_dir, process, timed_out, error, cleanup, owned, started)
    atomic_json(run_dir / 'metrics/result.json', result)
    failures = []
    if error:
        failures.append(error)
    if timed_out:
        failures.append('wall-clock budget exhausted')
    if cleanup:
        failures.append('owned process cleanup errors: ' + str(cleanup))
    if not result['route_records']:
        failures.append('no official route record')
    elif any(m in str(result['route_status']) for m in EXECUTION_FAILURE_STATUS):
        # 'Failed' alone (target not reached) or 'Failed - TickRuntime' are driving outcomes, kept as results.
        failures.append('official route status: ' + str(result['route_status']))
    if process is not None and process.returncode not in (0, None) and not timed_out:
        failures.append('evaluator exit code ' + str(process.returncode))
    if result['agent_summary'] is None:
        failures.append('agent summary missing (agent did not reach destroy)')
    run.record({'kind': 'framelease_v2_closed_loop_route', 'policy': args.policy, 'route_id': str(args.route_id),
                'seed': args.seed, 'kappa': args.kappa}, result, 'FAILED' if failures else 'COMPLETED',
               '; '.join(failures) or None)
    agent = result['agent_summary'] or {}
    report = canonical({'policy': args.policy, 'route': info, 'route_status': result['route_status'],
                        'scores': result['scores'], 'action_age_s': agent.get('action_age_s'),
                        'fallback_tick_ratio': agent.get('fallback_tick_ratio'), 'commits': agent.get('commits'),
                        'rejects': agent.get('rejects'), 'jobs': agent.get('jobs'), 'failures': failures})
    return run.finish('FAILED' if failures else 'COMPLETED', report, failures,
                      acceptance='PARTIAL' if not failures else 'FAILED')


if __name__ == '__main__':
    raise SystemExit(main())
