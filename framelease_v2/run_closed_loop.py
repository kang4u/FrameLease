#!/usr/bin/env python3
"""Run one Bench2Drive route in CARLA through the official leaderboard evaluator with the FrameLease
latency-aware agent (framelease_v2/latency_agent.py) under one scheduling policy.

Mirrors stage05_carla_closed_loop.run_native_benchmark: the official evaluator (with only stage05's narrowed
crash cleanup, native_evaluator_owned_cleanup) starts CARLA offscreen itself, runs in its own session, all child
processes are recorded and only processes this launcher owns are stopped. GPU work is serialized by the shared
writer lock (framelease_common.writer_lock on results/shared_gpu_resource).

  python framelease_v2/run_closed_loop.py --policy framelease --route-id 2086 \
      --routes third_party/UniDriveVLA-linux/Bench2Drive/bench2drive/leaderboard/data/routes_debug.xml \
      --kappa 1.0 --seed 11 --port 2400 --output-dir outputs/framelease_v2/closed_loop_smoke

--dry-run validates everything and prints the exact evaluator command without starting anything.
Outputs (StageRun ledger): <output-dir>/runs/<utc>_<id>/{config.json, manifest.json, report.md, source/,
logs/evaluator.log, raw/command.json, raw/agent_runtime_config.json, raw/official_results.json,
raw/agent/framelease/{ticks,jobs,events}.jsonl, raw/agent/framelease/summary.json, metrics/result.json}.
"""
