def _json_arg(text):
    if text is None:
        return {}
    if text.startswith('@'):
        text = Path(text[1:]).read_text(encoding='utf-8')
    value = json.loads(text)
    if not isinstance(value, dict):
        raise argparse.ArgumentTypeError('expected a JSON object')
    return value


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split('\n\n')[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--arm', required=True, choices=sorted(A.ARMS))
    p.add_argument('--routes', type=Path, default=ROOT / A.ROUTES_XML_REL, help='Bench2Drive routes XML')
    p.add_argument('--route-id', required=True)
    p.add_argument('--kappa', type=float, default=1.0)
    p.add_argument('--seed', type=int, default=11)
    p.add_argument('--port', type=int, default=2700, help='CARLA RPC port; +1, +2 and +6000 (TM) must be free')
    p.add_argument('--output-dir', type=Path, default=DEFAULT_OUTPUT)
    p.add_argument('--timeout-s', type=float, default=7200.0, help='wall-clock budget of the whole evaluation')
    p.add_argument('--evaluator-timeout', type=float, default=180.0, help="evaluator's --timeout (agent watchdog)")
    p.add_argument('--lock-wait-s', type=float, default=0.0, help='wait up to this long for the shared GPU lock')
    p.add_argument('--carla-root', type=Path, default=None, help='default: $CARLA_ROOT (as the v2 launcher)')
    p.add_argument('--checkpoint', type=Path, default=None, help='default: $CHECKPOINT (as the v2 launcher)')
    g = p.add_argument_group('fl_v3_heuristic only')
    g.add_argument('--lease-params', type=Path, help='base v2 LeaseParams file (ego shape; default envelope); '
                                                     'default: the arm\'s lease_params_q95_envelope.json')
    g.add_argument('--envelope', type=Path, help='residual envelope JSON replacing the default isotropic envelope')
    g.add_argument('--lease-overrides', type=_json_arg, default={}, help='SuffixLeaseConfig fields (JSON or @file)')
    g.add_argument('--policy-params', type=_json_arg, default={}, help='ShieldedHeuristicPolicy.PARAMS (JSON or @file)')
    g.add_argument('--runtime-params', type=_json_arg, default={}, help='RuntimeConfig overrides (JSON or @file)')
    p.add_argument('--dry-run', action='store_true')
    args = p.parse_args(argv)
    arm = A.ARMS[args.arm]
    if not arm.is_v3:
        given = [n for n in ('lease_params', 'envelope') if getattr(args, n) is not None]
        given += [n for n in ('lease_overrides', 'policy_params', 'runtime_params') if getattr(args, n)]
        if given:
            p.error(f'{args.arm} reproduces the v2 arm {arm.v2_arm} exactly; options {given} apply to fl_v3_heuristic only')
    return args


