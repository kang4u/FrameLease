#!/usr/bin/env python3
"""Run one Bench2Drive route in CARLA (official leaderboard evaluator) under one arm of the v3 closed-loop matrix.

  python framelease_v3/runtime/run_closed_loop_v3.py --arm fl_v3_heuristic --route-id 2086 --kappa 1.0 --seed 11 \
      --port 2800 --output-dir outputs/framelease_v3/closed_loop/pilot [--envelope ENVELOPE.json] [--dry-run]

Arms (v3_arms.py):
* fast_only, fixed_deep, fixed_deep_age2.0, fl_global: delegated to the UNCHANGED framelease_v2 launcher, i.e.
  framelease_v2.run_closed_loop.main(argv) in this process, with exactly the argument list that
  framelease_v2/closed_loop_matrix.py generates for the corresponding v2 arm (only --route-id, --port, --output-dir and
  the wall-clock options differ). The run directory, agent entry, agent configuration, evaluator command and
  environment are therefore produced by v2 code and the agent process runs only v2 code.
* fl_v3_heuristic: mirrors framelease_v2.run_closed_loop.main step by step (StageRun ledger, the stage05 crash-cleanup
  patch of the evaluator, shared GPU lock, port check, wall-clock budget, owned-process cleanup, result.json, report)
  with two differences: the evaluator loads raw/framelease_v3_agent_entry.py (framelease_v3.runtime.v3_agent:
  FrameLeaseLatencyAgent with a v3 setup()), configured by raw/agent_runtime_config.json = {"agent": AgentConfig,
  "v3": lease / envelope / policy block} through $FRAMELEASE_V3_RUNTIME_CONFIG ($FRAMELEASE_V2_RUNTIME_CONFIG is
  removed from the evaluator environment). The v3 runtime sources are additionally frozen under raw/source_v3/.

Outputs: <output-dir>/runs/<utc>_<id>/ with the v2 layout (config.json, manifest.json, report.md, source/,
logs/evaluator.log, raw/{command.json, agent_runtime_config.json, official_results.json},
raw/agent/framelease/{ticks,jobs,events,decisions}.jsonl, raw/agent/framelease/summary.json, metrics/result.json), so
framelease_v2/gpu_queue.py classifies v3 runs exactly like v2 runs. --dry-run validates everything (CPU only) and
prints the evaluator command without starting anything.
"""
