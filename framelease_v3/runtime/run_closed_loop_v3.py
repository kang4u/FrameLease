def v2_namespace(args, lease_params):
    """The fields framelease_v2.run_closed_loop helpers read (preflight, evaluator_command, evaluator_env)."""
    carla_root = args.carla_root or Path(os.environ.get('CARLA_ROOT', '/home/kang/opt/CARLA_0.9.15'))
    checkpoint = args.checkpoint or (Path(os.environ['CHECKPOINT']) if os.environ.get('CHECKPOINT') else None)
    return SimpleNamespace(policy=A.V3_MODE, routes=args.routes, route_id=str(args.route_id), kappa=args.kappa,
                           seed=args.seed, port=args.port, output_dir=args.output_dir, lease_params=lease_params,
                           carla_root=carla_root, checkpoint=checkpoint, timeout_s=args.timeout_s,
                           evaluator_timeout=args.evaluator_timeout, lock_wait_s=args.lock_wait_s)


def v3_configs(args):
    """(agent configuration dict for $FRAMELEASE_V3_RUNTIME_CONFIG, lease_params path, envelope path).

    Validates everything by building the policy exactly as the agent will (CPU only, no model)."""
    from framelease_v3.runtime import v3_lease as VL
    from framelease_v3.runtime import v3_scheduler as S
    arm = A.ARMS[args.arm]
    lease_params = (args.lease_params or (ROOT / arm.lease_params)).resolve()
    envelope = args.envelope.resolve() if args.envelope else None
    if 'kappa' in args.runtime_params and float(args.runtime_params['kappa']) != float(args.kappa):
        raise ValueError('kappa given twice with different values (--kappa and --runtime-params)')
    runtime = RuntimeConfig.from_dict({'kappa': float(args.kappa), **(arm.runtime_params or {}),
                                       **args.runtime_params}).to_dict()
    policy_params = {**arm.v3_policy_params, **args.policy_params}
    v3 = {'schema': S.SCHEMA, 'policy': arm.policy, 'policy_params': policy_params, 'lease': dict(args.lease_overrides),
          'lease_params_path': str(lease_params), 'lease_params_sha256': VL.sha256_file(lease_params),
          'envelope_path': str(envelope) if envelope else None,
          'envelope_sha256': VL.sha256_file(envelope) if envelope else None}
    policy = S.make_v3_policy(v3)
    v3['resolved'] = {'lease': policy.env.cfg.to_dict(), 'envelope': policy.env.envelope.describe(),
                      'policy_params': policy.params, 'ego': policy.env.ego.to_dict()}
    agent = AgentConfig(mode=arm.policy, policy_params=dict(policy_params), runtime=runtime, seed=int(args.seed),
                        temporal_mode='latest', precision='bf16-autocast', prompt_command='official',
                        lease_params_path=str(lease_params), warmup=True, record_metric_info=True).to_dict()
    full = {'agent': agent, 'v3': v3}
    agent_config_from(json.loads(json.dumps(full)))          # the agent's own validation, after a JSON round trip
    return jsonable(full), lease_params, envelope


def evaluator_command_v3(ns, run_dir, checkpoint):
    cmd = R2.evaluator_command(ns, run_dir, checkpoint)
    i = cmd.index('--agent')
    cmd[i + 1] = str(run_dir / 'raw' / ENTRY_NAME)
    return cmd


def evaluator_env_v3(ns, run_dir):
    env, overrides = R2.evaluator_env(ns, run_dir)
    env.pop(ENV_RUNTIME_CONFIG, None)
    overrides.pop(ENV_RUNTIME_CONFIG, None)
    env[ENV_V3_CONFIG] = overrides[ENV_V3_CONFIG] = str(run_dir / 'raw' / 'agent_runtime_config.json')
    return env, overrides


def code_dependencies_v3(ns, lease_params, envelope):
    deps = [ROOT / d for d in R2.CODE_DEPENDENCIES if (ROOT / d).is_file()]
    deps += [ROOT / d for d in V3_CODE if (ROOT / d).is_file() and d != STAGE + '.py']
    deps += [R2.EVALUATOR, R2.OFFICIAL_AGENT, R2.OFFICIAL_AGENT.with_name('pid_controller.py'), R2.MODEL_CONFIG,
             Path(ns.routes).resolve(), Path(lease_params)]
    if envelope:
        deps.append(Path(envelope))
    return deps


def freeze_v3_sources(raw, lease_params, envelope):
    """Byte copies under raw/source_v3/<relative path> (StageRun's source/ keys by basename, so __init__.py collide)."""
    out = {}
    for rel in V3_CODE:
        src = ROOT / rel
        if src.is_file():
            dst = raw / 'source_v3' / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dst)
            out[rel] = file_hash(dst)
    for p, name in ((lease_params, 'lease_params.json'), (envelope, 'envelope.json')):
        if p:
            dst = raw / 'source_v3' / name
            shutil.copyfile(p, dst)
            out[name] = file_hash(dst)
    return out


def preflight_v3(ns, lease_params, envelope):
    problems = []
    for rel in V3_CODE:
        if not (ROOT / rel).is_file() and rel != 'framelease_v3/__init__.py':
            problems.append(f'v3 runtime file missing: {rel}')
    if envelope and not Path(envelope).is_file():
        problems.append(f'envelope not found: {envelope}')
    if problems:
        raise SystemExit('preflight failed:\n  ' + '\n  '.join(problems))
    return R2.preflight(ns)


def run_v3(args):
    args.output_dir = args.output_dir.resolve()
    try:
        cfg, lease_params, envelope = v3_configs(args)
        ns = v2_namespace(args, lease_params)
        info = preflight_v3(ns, lease_params, envelope)
    except ValueError as e:
        raise SystemExit(f'invalid configuration: {e}')
    arm = A.ARMS[args.arm]
    clock = 'VIRTUAL_TIME_MEASURED_LATENCY'
    if args.dry_run:
        placeholder = args.output_dir / 'runs' / '<UTC>_<ID>'
        env, overrides = evaluator_env_v3(ns, placeholder)
        print(json.dumps({'status': 'NOT_STARTED', 'dry_run': True, 'arm': args.arm, 'policy': arm.policy,
                          'title': arm.title, 'clock': clock, 'route': info, 'agent_runtime_config': cfg,
                          'cwd': str(R2.B2D), 'command': evaluator_command_v3(ns, placeholder, ns.checkpoint),
                          'environment_overrides': overrides,
                          'ports': [args.port, args.port + 1, args.port + 2, args.port + 6000]}, indent=1))
        return 0

    from stage02_real_vla import UNIDRIVE_COMMIT
    from stage05_carla_closed_loop import native_evaluator_owned_cleanup, require_free_ports, stop_owned_group
    import psutil

    checkpoint = ns.checkpoint.resolve()
    hash_cache = args.output_dir / '.file_hash_cache.json'
    args.output_dir.mkdir(parents=True, exist_ok=True)
    v3 = cfg['v3']
    config = {'mode': 'closed-loop', 'arm': args.arm, 'policy': arm.policy, 'title': arm.title, 'clock': clock,
              'route': info, 'lease_h_max_s': v3['resolved']['lease']['h_bar_s'], 'max_age_note': None,
              'routes': str(Path(args.routes).resolve()), 'routes_sha256': file_hash(args.routes),
              'kappa': args.kappa, 'seed': args.seed, 'port': args.port, 'tm_port': args.port + 6000,
              'agent_config': cfg['agent'], 'v3': v3, 'checkpoint': str(checkpoint),
              'checkpoint_sha256': R2.cached_file_hash(checkpoint, hash_cache),
              'lease_params_sha256': v3['lease_params_sha256'], 'envelope_sha256': v3['envelope_sha256'],
              'model_source_commit': UNIDRIVE_COMMIT, 'evaluator_sha256': file_hash(R2.EVALUATOR),
              'official_agent_sha256': file_hash(R2.OFFICIAL_AGENT), 'wall_timeout_s': args.timeout_s,
              'ground_truth_contract': 'simulator state only in the official scorer and in evaluation-only '
                                       'metric_info; never in the model input, the lease, the shield or the controller'}
    evidence = ['CARLA_CLOSED_LOOP', 'REAL_VLA', 'REAL_GPU', clock, 'FRAMELEASE_V3']
    sns = SimpleNamespace(output_dir=args.output_dir, seed=args.seed, mode='closed-loop', resume=False)
    run = StageRun(STAGE, sns, config, evidence, code_dependencies_v3(ns, lease_params, envelope))
    run_dir = run.path.resolve()
    raw = run_dir / 'raw'
    (raw / 'agent').mkdir(parents=True, exist_ok=True)
    frozen = freeze_v3_sources(raw, lease_params, envelope)
    atomic_json(raw / 'source_v3' / 'hashes.json', frozen)
    atomic_json(raw / 'agent_runtime_config.json', cfg)
    (raw / ENTRY_NAME).write_text(ENTRY_SOURCE, encoding='utf-8')
    original = R2.EVALUATOR.read_text()
    patched = native_evaluator_owned_cleanup(original)
    (raw / 'leaderboard_evaluator_owned.py').write_text(patched)
    (raw / 'evaluator_cleanup.patch').write_text(''.join(difflib.unified_diff(
        original.splitlines(True), patched.splitlines(True), fromfile=str(R2.EVALUATOR),
        tofile=str(raw / 'leaderboard_evaluator_owned.py'))))
    cmd = evaluator_command_v3(ns, run_dir, checkpoint)
    env, overrides = evaluator_env_v3(ns, run_dir)
    atomic_json(raw / 'command.json', {'argv': cmd, 'cwd': str(R2.B2D), 'environment_overrides': overrides,
                                       'patched_evaluator_sha256': file_hash(raw / 'leaderboard_evaluator_owned.py')})

    # ---- execution: framelease_v2.run_closed_loop.main, unchanged logic
    process = None
    owned = {}
    error = None
    timed_out = False
    cleanup = []
    started = time.monotonic()
    try:
        with R2.gpu_lock(args.lock_wait_s, run.log):
            try:
                require_free_ports([args.port, args.port + 1, args.port + 2, args.port + 6000])
                with (run_dir / 'logs/evaluator.log').open('w') as log:
                    process = subprocess.Popen(cmd, cwd=R2.B2D, env=env, stdout=log, stderr=subprocess.STDOUT,
                                               start_new_session=True)
                run.log('evaluator_started', pid=process.pid)
                while process.poll() is None:
                    try:
                        for child in psutil.Process(process.pid).children(recursive=True):
                            owned[child.pid] = child.create_time()
                    except psutil.NoSuchProcess:
                        pass
                    if time.monotonic() - started > args.timeout_s:
                        timed_out = True
                        break
                    time.sleep(2)
            except BaseException:
                error = traceback.format_exc()
                run.log('failure', traceback=error)
            finally:
                if process is not None:
                    try:
                        stop_owned_group(process)
                    except Exception as e:  # noqa: BLE001
                        cleanup.append(repr(e))
                for pid, created in owned.items():
                    try:
                        child = psutil.Process(pid)
                        if child.create_time() == created and child.status() != psutil.STATUS_ZOMBIE:
                            child.kill()
                            child.wait(timeout=10)
                    except psutil.NoSuchProcess:
                        pass
                    except Exception as e:  # noqa: BLE001
                        cleanup.append(repr(e))
    except BaseException:
        error = error or traceback.format_exc()
        run.log('failure', traceback=error)

    result = R2.summarize(run_dir, process, timed_out, error, cleanup, owned, started)
    atomic_json(run_dir / 'metrics/result.json', result)
    failures = []
    if error:
        failures.append(error)
    if timed_out:
        failures.append('wall-clock budget exhausted')
    if cleanup:
        failures.append('owned process cleanup errors: ' + str(cleanup))
    if not result['route_records']:
        failures.append('no official route record')
    elif any(m in str(result['route_status']) for m in R2.EXECUTION_FAILURE_STATUS):
        failures.append('official route status: ' + str(result['route_status']))
    if process is not None and process.returncode not in (0, None) and not timed_out:
        failures.append('evaluator exit code ' + str(process.returncode))
    if result['agent_summary'] is None:
        failures.append('agent summary missing (agent did not reach destroy)')
    run.record({'kind': 'framelease_v3_closed_loop_route', 'arm': args.arm, 'policy': arm.policy,
                'route_id': str(args.route_id), 'seed': args.seed, 'kappa': args.kappa}, result,
               'FAILED' if failures else 'COMPLETED', '; '.join(failures) or None)
    agent = result['agent_summary'] or {}
    v3s = agent.get('v3') or {}
    report = canonical({'arm': args.arm, 'policy': arm.policy, 'route': info, 'route_status': result['route_status'],
                        'scores': result['scores'], 'action_age_s': agent.get('action_age_s'),
                        'fallback_tick_ratio': agent.get('fallback_tick_ratio'), 'commits': agent.get('commits'),
                        'rejects': agent.get('rejects'), 'jobs': agent.get('jobs'),
                        'p_both': v3s.get('p_both'), 'deadline_miss_tick_ratio': v3s.get('deadline_miss_tick_ratio'),
                        'shield_violations': v3s.get('shield_violations'), 'actions': v3s.get('actions'),
                        'lease_s': v3s.get('lease_s'), 'failures': failures})
    return run.finish('FAILED' if failures else 'COMPLETED', report, failures,
                      acceptance='PARTIAL' if not failures else 'FAILED')


def main(argv=None):
    args = parse_args(argv)
    if A.ARMS[args.arm].is_v3:
        return run_v3(args)
    return run_baseline(args)


if __name__ == '__main__':
    raise SystemExit(main())
