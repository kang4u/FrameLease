# ============================================================================================ execution (copied from v2)

def execute(run, run_dir, cmd, env, ports, timeout_s, lock_wait_s):
    """framelease_v2/run_closed_loop.py main(): shared GPU lock, port check, evaluator, owned-process cleanup."""
    from stage05_carla_closed_loop import require_free_ports, stop_owned_group
    import psutil
    process = None
    owned = {}
    error = None
    timed_out = False
    cleanup = []
    started = time.monotonic()
    try:
        with R2.gpu_lock(lock_wait_s, run.log):
            try:
                require_free_ports(ports)
                with (run_dir / 'logs/evaluator.log').open('w') as log:
                    process = subprocess.Popen(cmd, cwd=R2.B2D, env=env, stdout=log, stderr=subprocess.STDOUT,
                                               start_new_session=True)
                run.log('evaluator_started', pid=process.pid)
                while process.poll() is None:
                    try:
                        for child in psutil.Process(process.pid).children(recursive=True):
                            owned[child.pid] = child.create_time()
                    except psutil.NoSuchProcess:
                        pass
                    if time.monotonic() - started > timeout_s:
                        timed_out = True
                        break
                    time.sleep(2)
            except BaseException:
                error = traceback.format_exc()
                run.log('failure', traceback=error)
            finally:
                if process is not None:
                    try:
                        stop_owned_group(process)
                    except Exception as e:  # noqa: BLE001
                        cleanup.append(repr(e))
                for pid, created in owned.items():
                    try:
                        child = psutil.Process(pid)
                        if child.create_time() == created and child.status() != psutil.STATUS_ZOMBIE:
                            child.kill()
                            child.wait(timeout=10)
                    except psutil.NoSuchProcess:
                        pass
                    except Exception as e:  # noqa: BLE001
                        cleanup.append(repr(e))
    except BaseException:
        error = error or traceback.format_exc()
        run.log('failure', traceback=error)
    return process, owned, error, timed_out, cleanup, started


def fast_prefix_outcome(run_dir, fp):
    """(manifest or None, problems): the agent's own record of what ran."""
    path = run_dir / 'raw' / 'agent' / 'framelease' / AE.MANIFEST_NAME
    if not path.is_file():
        return None, ['fast-prefix manifest missing (agent setup did not complete)']
    try:
        man = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError) as e:
        return None, [f'fast-prefix manifest unreadable: {e}']
    problems = []
    active = (man.get('fast_prefix') or {}).get('active') or {}
    for opt in FP.OPTIONS:
        if bool(active.get(opt)) != (opt in fp['options']):
            problems.append(f'fast prefix option {opt}: active={active.get(opt)}, configured={opt in fp["options"]}')
    val = (man.get('fast_prefix') or {}).get('validation')
    if fp['validate'] and fp['options']:
        if val is None:
            problems.append('fast prefix not validated (warm-up did not run)')
        elif not val.get('ok'):
            problems.append('fast prefix validation failed: ' + '; '.join(val.get('failures') or []))
    return man, problems


def run(own, base):
    prep = prepare(own, base)
    fp = prep['fp']
    if base.dry_run:
        placeholder = base.output_dir / 'runs' / '<UTC>_<ID>'
        env, overrides = evaluator_env(prep, placeholder)
        print(json.dumps({'status': 'NOT_STARTED', 'dry_run': True, 'arm': fp['arm'], 'base_arm': base.arm,
                          'policy': prep['arm'].policy, 'base_kind': prep['kind'], 'route': prep['route'],
                          'agent_runtime_config': prep['agent_runtime_config'], 'fast_prefix_config': fp,
                          'cwd': str(R2.B2D), 'command': evaluator_command(prep, placeholder, prep['ns'].checkpoint),
                          'environment_overrides': overrides,
                          'ports': [base.port, base.port + 1, base.port + 2, base.port + 6000]}, indent=1, default=str))
        return 0
    from stage05_carla_closed_loop import native_evaluator_owned_cleanup
    checkpoint = Path(prep['ns'].checkpoint).resolve()
    base.output_dir.mkdir(parents=True, exist_ok=True)
    hash_cache = base.output_dir / '.file_hash_cache.json'
    config = base_config(prep, base, checkpoint, hash_cache)
    evidence = ['CARLA_CLOSED_LOOP', 'REAL_VLA', 'REAL_GPU', 'VIRTUAL_TIME_MEASURED_LATENCY', 'FAST_PREFIX']
    if prep['kind'] == 'v3':
        evidence.insert(4, 'FRAMELEASE_V3')
    sns = SimpleNamespace(output_dir=base.output_dir, seed=base.seed, mode='closed-loop', resume=False)
    srun = StageRun(STAGE, sns, config, evidence, code_dependencies(prep))
    run_dir = srun.path.resolve()
    raw = run_dir / 'raw'
    (raw / 'agent').mkdir(parents=True, exist_ok=True)
    if prep['kind'] == 'v3':
        atomic_json(raw / 'source_v3' / 'hashes.json', L.freeze_v3_sources(raw, prep['lease_params'], prep['envelope']))
    atomic_json(raw / 'source_fastprefix' / 'hashes.json', freeze_fastprefix_sources(raw))
    atomic_json(raw / 'agent_runtime_config.json', prep['agent_runtime_config'])
    atomic_json(raw / CONFIG_NAME, fp)
    (raw / ENTRY_NAME).write_text(ENTRY_SOURCE, encoding='utf-8')
    original = R2.EVALUATOR.read_text()
    patched = native_evaluator_owned_cleanup(original)
    (raw / 'leaderboard_evaluator_owned.py').write_text(patched)
    (raw / 'evaluator_cleanup.patch').write_text(''.join(difflib.unified_diff(
        original.splitlines(True), patched.splitlines(True), fromfile=str(R2.EVALUATOR),
        tofile=str(raw / 'leaderboard_evaluator_owned.py'))))
    cmd = evaluator_command(prep, run_dir, checkpoint)
    env, overrides = evaluator_env(prep, run_dir)
    atomic_json(raw / 'command.json', {'argv': cmd, 'cwd': str(R2.B2D), 'environment_overrides': overrides,
                                       'patched_evaluator_sha256': file_hash(raw / 'leaderboard_evaluator_owned.py')})
    ports = [base.port, base.port + 1, base.port + 2, base.port + 6000]
    process, owned, error, timed_out, cleanup, started = execute(srun, run_dir, cmd, env, ports, base.timeout_s,
                                                                  base.lock_wait_s)
    result = R2.summarize(run_dir, process, timed_out, error, cleanup, owned, started)
    manifest, fp_problems = fast_prefix_outcome(run_dir, fp)
    result['fast_prefix'] = {'config': fp, 'agent_manifest': manifest, 'problems': fp_problems}
    atomic_json(run_dir / 'metrics/result.json', result)
    failures = []
    if error:
        failures.append(error)
    if timed_out:
        failures.append('wall-clock budget exhausted')
    if cleanup:
        failures.append('owned process cleanup errors: ' + str(cleanup))
    if not result['route_records']:
        failures.append('no official route record')
    elif any(m in str(result['route_status']) for m in R2.EXECUTION_FAILURE_STATUS):
        failures.append('official route status: ' + str(result['route_status']))
    if process is not None and process.returncode not in (0, None) and not timed_out:
        failures.append('evaluator exit code ' + str(process.returncode))
    if result['agent_summary'] is None:
        failures.append('agent summary missing (agent did not reach destroy)')
    failures += fp_problems
    srun.record({'kind': 'framelease_v3_fastprefix_closed_loop_route', 'arm': fp['arm'], 'base_arm': base.arm,
                 'policy': prep['arm'].policy, 'route_id': str(base.route_id), 'seed': base.seed, 'kappa': base.kappa,
                 'fast_prefix': fp['options']}, result, 'FAILED' if failures else 'COMPLETED', '; '.join(failures) or None)
    agent = result['agent_summary'] or {}
    v3s = agent.get('v3') or {}
    report = canonical({'arm': fp['arm'], 'base_arm': base.arm, 'policy': prep['arm'].policy, 'route': prep['route'],
                        'route_status': result['route_status'], 'scores': result['scores'],
                        'action_age_s': agent.get('action_age_s'), 'fallback_tick_ratio': agent.get('fallback_tick_ratio'),
                        'commits': agent.get('commits'), 'rejects': agent.get('rejects'), 'jobs': agent.get('jobs'),
                        'prefix_cost_s': agent.get('prefix_cost_s'), 'step_cost_s': agent.get('step_cost_s'),
                        'p_both': v3s.get('p_both'), 'deadline_miss_tick_ratio': v3s.get('deadline_miss_tick_ratio'),
                        'fast_prefix': agent.get('fast_prefix'), 'failures': failures})
    return srun.finish('FAILED' if failures else 'COMPLETED', report, failures,
                       acceptance='PARTIAL' if not failures else 'FAILED')


def main(argv=None):
    own, base = parse_args(argv)
    return run(own, base)


if __name__ == '__main__':
    raise SystemExit(main())
