"""Run one Bench2Drive route under a v3-matrix arm WITH the fast prefix (FrameLease v3 R&D sprint 2026-11-10).

  python framelease_v3/fastprefix/run_closed_loop_fast.py [--fast-prefix all|none|sdpa,gpu_preproc,lora_merged] \
      [--no-validate] [--on-validation-failure raise|record] <run_closed_loop_v3.py arguments> [--dry-run]
  e.g. --arm fast_only --route-id 2086 --kappa 1.0 --seed 11 --port 2905 --output-dir DIR

Every argument except the three fast-prefix options is parsed by framelease_v3/runtime/run_closed_loop_v3.py's own
parser, and the base arm is configured by the unchanged base launchers' functions:
* baseline arms (fast_only, fixed_deep, fixed_deep_age2.0, fl_global): framelease_v2.run_closed_loop.agent_config /
  preflight / evaluator_command / evaluator_env on the argument list v3_arms.v2_launcher_argv gives for that arm, i.e.
  the agent configuration is byte for byte the one of the v2 arm; agent class FrameLeaseLatencyAgent.
* fl_v3_heuristic: run_closed_loop_v3.v3_configs / preflight_v3 / evaluator_command_v3 / evaluator_env_v3; agent class
  FrameLeaseV3Agent.
The only differences from the base launcher: the evaluator loads raw/framelease_v3_fastprefix_agent_entry.py
(framelease_v3.fastprefix.agent_entry: the base agent class + fast prefix at the end of setup()), the evaluator
environment has $FRAMELEASE_FASTPREFIX_CONFIG = raw/fast_prefix_config.json, the fast-prefix sources are frozen under
raw/source_fastprefix/, and config.json carries 'arm' (<arm>_fp), 'base_arm' and 'fast_prefix'. The prefix and flow
steps are still timed by the unchanged v2 backend (CUDA events) and charged as kappa x measured cost by the unchanged
runtime, so the simulated timeline uses the measured, faster costs. Execution, cleanup, result.json and report follow
framelease_v2/run_closed_loop.py main() (copied), so framelease_v2/gpu_queue.py classifies these runs like v2 runs.
"""
