def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def arm_label(arm, options):
    return f'{arm}_fp' if options else f'{arm}_fpnone'


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split('\n\n')[0], allow_abbrev=False,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--fast-prefix', default='all', help="'all' (= sdpa,gpu_preproc,lora_merged), 'none' or a list")
    p.add_argument('--no-validate', action='store_true', help='skip the warm-up validation window')
    p.add_argument('--on-validation-failure', choices=AE.ON_FAILURE, default='raise')
    own, rest = p.parse_known_args(argv)
    try:
        own.options = FP.parse_options(own.fast_prefix)
    except ValueError as e:
        p.error(str(e))
    base = L.parse_args(rest)
    return own, base


def fast_prefix_config(own, base_kind, arm):
    cfg = {'schema': AE.CONFIG_SCHEMA, 'base': base_kind, 'options': list(own.options), 'validate': not own.no_validate,
           'on_validation_failure': own.on_validation_failure, 'strict_sources': True,
           'fast_path_sha256': sha256(FP.__file__), 'expected_upstream_sha256': dict(FP.UPSTREAM_SOURCE_SHA256),
           'arm': arm_label(arm, own.options), 'base_arm': arm}
    return AE.normalize_config(json.loads(json.dumps(cfg)))


# ============================================================================================ base configuration

def prepare(own, base):
    """Everything the base launcher would build (CPU only). Returns a dict describing the run."""
    arm = A.ARMS[base.arm]
    base.output_dir = Path(base.output_dir).resolve()
    if arm.is_v3:
        try:
            cfg, lease_params, envelope = L.v3_configs(base)
            ns = L.v2_namespace(base, lease_params)
            info = L.preflight_v3(ns, lease_params, envelope)
        except ValueError as e:
            raise SystemExit(f'invalid configuration: {e}')
        return {'kind': 'v3', 'arm': arm, 'agent_runtime_config': cfg, 'ns': ns, 'route': info,
                'lease_params': lease_params, 'envelope': envelope, 'base_launcher': L.STAGE + '.py',
                'fp': fast_prefix_config(own, 'v3', base.arm)}
    argv = L.v2_argv(base)
    a2 = R2.parse_args([x for x in argv if x != '--dry-run'])
    a2.output_dir = Path(a2.output_dir).resolve()
    try:
        cfg = R2.agent_config(a2)
        info = R2.preflight(a2)
    except ValueError as e:
        raise SystemExit(f'invalid configuration: {e}')
    return {'kind': 'v2', 'arm': arm, 'agent_runtime_config': cfg, 'ns': a2, 'route': info, 'v2_argv': argv,
            'lease_params': a2.lease_params.resolve() if a2.lease_params else None, 'envelope': None,
            'base_launcher': R2.STAGE + '.py', 'fp': fast_prefix_config(own, 'v2', base.arm)}


def evaluator_command(prep, run_dir, checkpoint):
    if prep['kind'] == 'v3':
        cmd = L.evaluator_command_v3(prep['ns'], run_dir, checkpoint)
    else:
        cmd = R2.evaluator_command(prep['ns'], run_dir, checkpoint)
    i = cmd.index('--agent')
    cmd[i + 1] = str(run_dir / 'raw' / ENTRY_NAME)
    return cmd


def evaluator_env(prep, run_dir):
    if prep['kind'] == 'v3':
        env, overrides = L.evaluator_env_v3(prep['ns'], run_dir)
    else:
        env, overrides = R2.evaluator_env(prep['ns'], run_dir)
    env[AE.ENV_FASTPREFIX_CONFIG] = overrides[AE.ENV_FASTPREFIX_CONFIG] = str(run_dir / 'raw' / CONFIG_NAME)
    return env, overrides


def code_dependencies(prep):
    if prep['kind'] == 'v3':
        deps = L.code_dependencies_v3(prep['ns'], prep['lease_params'], prep['envelope'])
    else:
        deps = [ROOT / d for d in R2.CODE_DEPENDENCIES if (ROOT / d).is_file()]
        deps += [R2.EVALUATOR, R2.OFFICIAL_AGENT, R2.OFFICIAL_AGENT.with_name('pid_controller.py'), R2.MODEL_CONFIG,
                 Path(prep['ns'].routes).resolve()]
        if prep['lease_params']:
            deps.append(Path(prep['lease_params']))
    deps += [ROOT / d for d in FP_CODE if (ROOT / d).is_file() and d != STAGE + '.py']
    deps += [ROOT / d for d in UPSTREAM_FILES if (ROOT / d).is_file()]
    return deps


def freeze_fastprefix_sources(raw):
    out = {}
    for rel in FP_CODE + UPSTREAM_FILES:
        src = ROOT / rel
        if src.is_file():
            dst = raw / 'source_fastprefix' / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dst)
            out[rel] = file_hash(dst)
    return out


